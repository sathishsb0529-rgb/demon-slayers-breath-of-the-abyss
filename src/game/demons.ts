export interface DemonAbilitySpec {
  difficultyTier: DemonDifficultyTier;
  demonClass: DemonClassId;
  sfxTheme: DemonSfxTheme;
  preferredMinDist: number;
  preferredMaxDist: number;
  canBlock: boolean;
  dodgeChance: number;
  phases: 1 | 2 | 3 | 4;
  bdaCooldown: number;
  ultimateCooldown: number;
  cloneArchetype?: DemonArchetype;
  projectileKind: BdaProjectile['kind'];
  projectileSpeed: number;
  multiShotCount: number;
  areaKind: 'shockwave' | 'ice_field' | 'lightning_burst' | 'silk_prison' | 'swamp_erupt' | 'crimson_blast';
  ultimateKind: BdaProjectile['kind'];
  ultimateText: string;
  poisonDps?: number;
  chillDuration?: number;
  canTeleport?: boolean;
  triggersRoomShift?: boolean;
  bounces?: number;
}

